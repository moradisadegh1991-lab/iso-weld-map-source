#!/usr/bin/env node
/**
 * Writes lib/platform/tile-apis.mjs: the API routes each page calls, read
 * from the source (lib/platform/tile-scan.mjs). Run after adding or changing
 * a page's API calls: `npm run tiles:map`. db/test/tiles.mjs fails while the
 * file is out of date, so a page cannot start calling a route that the tile
 * check would refuse to people given that page.
 */
import fs from "node:fs";
import path from "node:path";
import { scanTileApis } from "../lib/platform/tile-scan.mjs";

export async function render(root = process.cwd()) {
  const { scannedPages } = await import(path.join(root, "lib/platform/tiles.mjs"));
  const map = scanTileApis(scannedPages(), root);
  const body = Object.entries(map).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
  return `// Generated by tools/tile-apis.mjs from the pages' source — do not edit; run \`npm run tiles:map\`.\n`
    + `// The API routes each page (tile) calls. lib/platform/tiles.mjs lets a member narrowed to tiles reach only these.\n`
    + `export const TILE_APIS = {\n${body}\n};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = path.join(process.cwd(), "lib/platform/tile-apis.mjs");
  fs.writeFileSync(out, await render());
  console.log(`wrote ${out}`);
}
