/** Browser smoke check; requires a dedicated DMW2 scenario and test credentials. */
import { createRequire } from "node:module";
const { chromium } = createRequire(import.meta.url)("playwright");
import assert from "node:assert/strict";
const CHROME = process.env.CHROME_PATH || "/opt/pw-browsers/chromium-1194/chrome-linux/chrome";
const BASE = process.env.BASE_URL || "http://localhost:3000";
const SHOT = process.env.SHOT_DIR || "/tmp/shots";
const { DRIVE_EMAIL: EMAIL, DRIVE_PASSWORD: PASSWORD } = process.env;
if (!EMAIL || !PASSWORD) { console.error("set DRIVE_EMAIL and DRIVE_PASSWORD"); process.exit(1); }
const b = await chromium.launch({ executablePath: CHROME });
const problems = [];
let failed = 0;
const check = (ok, what) => { console.log(ok ? "ok  " : "FAIL", what); if (!ok) failed++; };
const ctx = await b.newContext({ viewport: { width: 1500, height: 1000 } });
const page = await ctx.newPage();
page.on("pageerror", (e) => problems.push("pageerror: " + e.message));
page.on("console", (m) => { if (m.type() === "error" && !/40[0-9]|Failed to load resource|Failed to fetch RSC payload/.test(m.text())) problems.push("console: " + m.text()); });
const asked = [];
page.on("dialog", (d) => { asked.push(d.message()); d.accept(); });
await page.goto(BASE, { waitUntil: "networkidle" });
await page.fill("#email", EMAIL); await page.fill("#password", PASSWORD);
await page.click("button[type=submit]"); await page.waitForSelector(".shell");
const api = (path, body) => page.evaluate(async ([p, x]) => {
  const r = await fetch(p, x ? { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(x) } : {});
  const j = await r.json();
  if (!r.ok) throw new Error(`${p}: ${j.error}`);
  return j;
}, [path, body]);
await api("/api/auth/prefs", { lang: "en" });
await page.evaluate(() => localStorage.setItem("epc.prefs", JSON.stringify({ ...JSON.parse(localStorage.getItem("epc.prefs") || "{}"), lang: "en" })));
const me = await api("/api/auth/me");
const projectId = me.projects.find((p) => p.code === (process.env.DRIVE_PROJECT || "DMW2")).id;
const contractId = (await api(`/api/contract-reports?projectId=${projectId}`)).contracts[0].id;
await page.locator(".topbar select").selectOption(`c:${contractId}`); await page.waitForTimeout(500);

const tag = Date.now().toString(36).slice(-4).toUpperCase();
const pms = (await api("/api/eps", { projectId, kind: "pms", contractId, code: `PV-${tag}`, title: "Preview drive", budgetPlan: 1000 })).row;
const ver = (await api("/api/eps", { projectId, kind: "version", pmsId: pms.id, code: `PV-${tag}-R1`, title: "June" })).row;
const node = (await api("/api/eps", { projectId, kind: "node", pmsId: pms.id, name: "Piping", wf: 100, unit: "m", budgetPlan: 1000 })).row;
const mk = (name, wf, s, e, vol) => api("/api/eps", { projectId, kind: "activity", nodeId: node.id, name, wf, planStart: s, planEnd: e, volumePlan: vol, volumeActual: vol });
const A = (await mk("Spool erection", 50, "2026-01-01", "2026-01-10", 100)).row;
const B = (await mk("Support install", 30, "2026-01-05", "2026-01-15", 40)).row;
const C = (await mk("Hydrotest", 20, "2026-02-01", "2026-02-03", 3)).row;
await api("/api/eps/planning", { projectId, kind: "plan-add", versionId: ver.id, activityIds: [A.id, B.id] });

await page.goto(`${BASE}/eps/planning?version=${ver.id}`, { waitUntil: "networkidle" });
await page.locator(`tr[data-row="${A.code}"]`).first().waitFor();
await page.locator(`tr[data-row="${A.code}"]`).first().click();
await page.locator("[data-plan-history-table]").waitFor();
assert.equal(await page.locator("[data-plan-history-table] thead th").count(), 19);
assert.equal(await page.locator("[data-plan-version-comparison]").count(), 0);
assert.equal(await page.locator("[data-gantt-today]").getAttribute("stroke"), "#e11d48");
assert.equal(await page.locator(`[data-gantt="${A.code}"] rect`).first().count(), 1);
await page.goto(`${BASE}/eps/planning/preview?version=${ver.id}`, { waitUntil: "networkidle" });
await page.locator(`tr[data-row="${A.code}"]`).first().waitFor();
assert.equal(await page.locator("[data-gantt-today]").getAttribute("stroke"), "#e11d48");
assert.equal(await page.locator(`[data-gantt="${A.code}"] rect`).first().count(), 1);
// A future version starts the viewport at the planned start while today's marker remains on the timeline.
const nextPms = (await api("/api/eps", { projectId, kind: "pms", contractId, code: `PF-${tag}`, title: "Future drive" })).row;
const nextVer = (await api("/api/eps", { projectId, kind: "version", pmsId: nextPms.id, code: `PF-${tag}-R1`, title: "Future" })).row;
const nextNode = (await api("/api/eps", { projectId, kind: "node", pmsId: nextPms.id, name: "Future node", wf: 100 })).row;
const futureDay = (n) => new Date(Date.now() + n * 86400000).toISOString().slice(0, 10);
const nextAct = (await api("/api/eps", { projectId, kind: "activity", nodeId: nextNode.id, name: "Future activity", wf: 100, planStart: futureDay(180), planEnd: futureDay(190) })).row;
await api("/api/eps/planning", { projectId, kind: "plan-add", versionId: nextVer.id, activityIds: [nextAct.id], startOn: futureDay(200), endOn: futureDay(210) });
await page.goto(`${BASE}/eps/planning?version=${nextVer.id}`, { waitUntil: "networkidle" });
await page.locator(`tr[data-row="${nextAct.code}"]`).first().waitFor();
assert.equal(await page.locator("[data-gantt-today]").count(), 1);
assert((await page.locator(".p6-right").evaluate((el) => el.scrollLeft)) > 0, "future chart initially scrolls to planned start");
assert.equal(Number(await page.locator(`[data-gantt="${nextAct.code}"] rect`).first().getAttribute("x")), 200 * 22, "version dates set the chart scale and bar");
const emptyPms = (await api("/api/eps", { projectId, kind: "pms", contractId, code: `PE-${tag}`, title: "Undated drive" })).row;
const emptyVer = (await api("/api/eps", { projectId, kind: "version", pmsId: emptyPms.id, code: `PE-${tag}-R1`, title: "Undated" })).row;
const emptyNode = (await api("/api/eps", { projectId, kind: "node", pmsId: emptyPms.id, name: "Undated node", wf: 100 })).row;
const emptyAct = (await api("/api/eps", { projectId, kind: "activity", nodeId: emptyNode.id, name: "Undated activity", wf: 100 })).row;
await page.goto(`${BASE}/eps/planning?version=${emptyVer.id}`, { waitUntil: "networkidle" });
await page.locator(`tr[data-row="${emptyAct.code}"]`).first().waitFor();
assert.equal(await page.locator("[data-gantt-today]").getAttribute("x1"), "0");
assert.deepEqual(problems, []);
console.log("Planning history and both Gantt views: passed");
await b.close();
