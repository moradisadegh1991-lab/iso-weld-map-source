  w("- **Punch و NCR:** A و B بسته، C (تاچ‌آپ رنگ) باز — به تحویل منتقل می‌شود.");
  w("- **تحویل به نگهداری:** P-7001 «آماده» با DMW-70-P-7001؛ D-7002 «ناقص» با نام آنچه کم است (مدل، سریال، دفترچهٔ فروشنده، برنامهٔ PM).");
  w("- **کنترل پروژه و گزارش‌ها:** پیشرفت هر رشته از همین رکوردها حساب شده، نه از درصدی که کسی تایپ کرده باشد.");
  w();
  w("## ۶. اگر چیزی رد شد");
  w();
  w("پلتفرم هر رد را با دلیلش می‌گوید. رایج‌ترین‌ها در این سناریو:");
  w();
  w("| پیام (خلاصه) | یعنی | چه باید کرد |");
  w("|---|---|---|");
  for (const [m, why, fix] of TROUBLE) w(`| ${m} | ${why} | ${fix} |`);
  w();
  w("اگر پیامی دیدید که در گام «باید رد شود» نیامده و در این جدول هم نیست، شمارهٔ گام و متن پیام را یادداشت کنید — یا راهنما اشتباه است یا پلتفرم.");
  w();
  w("## ۷. پیوست — JSON ایزومتریک DMW-ISO-7001 (گام 5.2)");
  w();
  w("پس از «ورود دستی (JSON) برای همین نقشه»، این را در تب JSON بچسبانید و «اعمال محلی» بزنید:");
  w();
  w("```json");
  w(JSON.stringify(ISO_7001, null, 2));
  w("```");
  w();
  w("## ۸. آنچه این سناریو در پلتفرم پیدا کرد (و رفع شد)");
  w();
  w("- **FAT روی PO حاصل از مناقصه:** ردیف MR پرچم «FAT لازم» نداشت و PO ساخته‌شده از واگذاری هیچ‌وقت FAT نمی‌خواست — پمپی که از مناقصه خریده می‌شد بدون بازرسی کارخانه حمل می‌شد. حالا ردیف MR این پرچم را دارد و به ردیف PO منتقل می‌شود (مهاجرت ۰۵۰).");
  w("- **خطِ ایزومتریک ذخیره‌شده از صفحهٔ پایپینگ:** رجیستر هیچ «خط»ی نمی‌ساخت؛ جوش‌ها به خطی وصل نبودند، پس در پکیج تست و ساب‌سیستم نمی‌رفتند و MC آن‌ها را نمی‌دید (دمو خط را مستقیم در دیتابیس می‌ساخت). حالا ذخیره خط را می‌سازد، اگر ایزومتریک در MDR زیر ساب‌سیستمی باشد خط را همان‌جا ثبت می‌کند، و تجهیز خط را از اولین تای‌این نقشه می‌شناسد؛ خط‌های بی‌ساب‌سیستم هم در صفحهٔ «سیستم و ساب‌سیستم» با فرم ثبت نشان داده می‌شوند.");
