  w("- **تکمیل و راه‌اندازی › تست فشار و MC:** 70-01 «MC پذیرفته»؛ TP-70-01 با تست پذیرفتهٔ 24.5 barg (و تست ردشدهٔ 20 barg در سابقه).");
