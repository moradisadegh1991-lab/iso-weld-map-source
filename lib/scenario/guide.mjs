  w();
  w("### تقویم");
  w();
  w("اسکریپت در پایان، تاریخ واقعی همهٔ روزهای زیر را چاپ می‌کند. روزهایی که هر فاز به کار می‌برد:");
  w();
  w("| فاز | روزها |");
  w("|---|---|");
  for (const [k, title] of PHASES) {
    const days = daysOf(STEPS.filter((y) => y.phase === k));
    w(`| ${k} — ${title} | ${days.length ? days.join("، ") : "—"} |`);
  }
  w();
  w("### افراد");
  w();
  w("پلتفرم نمی‌گذارد کسی که امضا می‌کند همان کار را بپذیرد؛ پس سناریو سه نفر لازم دارد. اسکریپت دو حساب دیگر را می‌سازد و رمزشان را **یک بار** چاپ می‌کند:");
  w();
  w("| نقش در سناریو | نقش در پلتفرم | طرف بازرسی | ورود |");
  w("|---|---|---|---|");
