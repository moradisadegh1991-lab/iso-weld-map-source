/**
 * The DM-water pump scenario as a guide for a person, in Persian — written
 * from the same steps the test plays (lib/scenario/dm-pump.mjs), so the
 * guide cannot promise what the platform does not do.
 */
import { SCENARIO, PEOPLE, PHASES, STEPS, ISO_7001 } from "./dm-pump.mjs";

export function guideMarkdown() {
  const out = [];
  const w = (s = "") => out.push(s);
  const negatives = STEPS.filter((s) => s.negative).length;

  w("# سناریوی آزمون کل پلتفرم — پمپ آب DM به درام");
  w();
  w("> این فایل از `lib/scenario/dm-pump.mjs` ساخته می‌شود (`npm run scenario:dm -- --doc`)؛ دستی ویرایش نکنید.");
  w("> همان گام‌ها در `db/test/scenario-dm.mjs` روی دیتابیس خالی اجرا می‌شوند — هر گام این راهنما، و هر ردی که پیش‌بینی کرده، آزموده شده است.");
  w();
  w("## ۱. سیستم");
  w();
  w("پمپ گریز از مرکز **P-7001** آب دمین (DM) را از طریق خط **70-DMW-7001** (۳ اینچ، کلاس A1DM) به درام افقی **D-7002** می‌فرستد؛");
  w("فلو ترانسمیتر **FT-7001** روی خروجی پمپ و لول ترانسمیتر **LT-7002** روی درام است. همه در واحد 70 و ساب‌سیستم **70-01**.");
  w();
  w("```");
  w("   [D-7002]  ◄── 70-DMW-7001 (3\" SCH40, A1DM) ── FT-7001 ── [P-7001] ◄ MCC-70 (CBL-P-7001)");
  w("   LT-7002                                                  ");
  w("```");
  w();
  w(`سناریو **${STEPS.length} گام در ${PHASES.length} فاز** دارد؛ **${negatives} گام «آزمون منفی»** است: کاری که پلتفرم باید رد کند، و ردش — با همان دلیلی که نوشته شده — نتیجهٔ درست است.`);
  w();
  w("## ۲. شروع");
  w();
  w("```bash");
  w("npm run scenario:dm -- <ایمیل شما>              # پروژهٔ تازهٔ DMW، آماده برای گام 0.2 — بقیه را خودتان انجام دهید");
  w("npm run scenario:dm -- <ایمیل شما> --upto 4.5    # همان، با گام‌های تا 4.5 از پیش انجام‌شده (برای دیدن یک مرحله)");
  w("npm run scenario:dm -- <ایمیل شما> --upto all    # کل کار، برای دیدن وضعیت پایانی");
  w("```");
  w();
  w("- هر اجرا یک **پروژهٔ جدید** می‌سازد (DMW، بعد DMW2، …)؛ به پروژه‌های قبلی دست نمی‌زند.");
  w("- **روز N**: اسکریپت «روز 0» را چاپ می‌کند (حدود ۱۵۰ روز پیش). هر جا راهنما «روز N» می‌گوید، تاریخ روز 0 به‌علاوهٔ N را وارد کنید — تا همهٔ کار در گذشته باشد و مثلاً شکست ۲۸ روزهٔ بتن قابل ثبت باشد.");
  w("- **استثنا:** زمانِ درخواست بازرسی (IR) باید واقعاً در آینده باشد؛ آن را با ساعت واقعی فردا ثبت کنید.");
  w();
  w("### افراد");
  w();
  w("پلتفرم نمی‌گذارد کسی که امضا می‌کند همان کار را بپذیرد؛ پس سناریو سه نفر لازم دارد. اسکریپت دو حساب دیگر را می‌سازد و رمزشان را **یک بار** چاپ می‌کند:");
  w();
  w("| نقش در سناریو | نقش در پلتفرم | طرف بازرسی | ورود |");
  w("|---|---|---|---|");
  for (const p of Object.values(PEOPLE)) w(`| ${p.title} | ${p.role} | ${PARTY_FA[p.party]} | ${p.email ? `\`${p.email}\`` : "حساب خودتان"} |`);
  w();
  w("برای عوض کردن نفر، از منوی حساب خارج شوید و با حساب دیگر وارد شوید (یا یک پنجرهٔ خصوصی مرورگر باز کنید).");
  w();
  w("## ۳. گام‌ها");
  w();
  w("هر گام: **چه کسی**، **کجا** در پلتفرم، **چه چیزی** وارد شود، و **باید ببینید**. کنار هر گام تیک بزنید.");
  w();
  for (const [k, title] of PHASES) {
    w(`### فاز ${k} — ${title}`);
    w();
    for (const s of STEPS.filter((y) => y.phase === k)) {
      w(`#### ${s.negative ? "⛔ " : ""}${s.id} · ${s.title}`);
      w();
      w("- [ ] انجام شد");
      w();
      w(`**چه کسی:** ${PEOPLE[s.who].title}  `);
      w(`**کجا:** ${s.where}`);
      w();
      w(s.negative ? "**امتحان کنید:**" : "**انجام دهید:**");
      for (const d of s.do) w(`- ${d}`);
      w();
      w(s.negative ? "**باید رد شود:**" : "**باید ببینید:**");
      for (const e of s.expect) w(`- ${e}`);
      w();
    }
  }
  w("## ۴. پیوست — JSON ایزومتریک DMW-ISO-7001 (گام 5.2)");
  w();
  w("در صفحهٔ پایپینگ، تب JSON، این را بچسبانید و «اعمال» بزنید:");
  w();
  w("```json");
  w(JSON.stringify(ISO_7001, null, 2));
  w("```");
  w();
  w("## ۵. آنچه این سناریو در پلتفرم پیدا کرد (و رفع شد)");
  w();
  w("- **FAT روی PO حاصل از مناقصه:** ردیف MR پرچم «FAT لازم» نداشت و PO ساخته‌شده از واگذاری هیچ‌وقت FAT نمی‌خواست — پمپی که از مناقصه خریده می‌شد بدون بازرسی کارخانه حمل می‌شد. حالا ردیف MR این پرچم را دارد و به ردیف PO منتقل می‌شود (مهاجرت ۰۵۰).");
  w("- **خطِ ایزومتریک ذخیره‌شده از صفحهٔ پایپینگ:** رجیستر هیچ «خط»ی نمی‌ساخت؛ جوش‌ها به خطی وصل نبودند، پس در پکیج تست و ساب‌سیستم نمی‌رفتند و MC آن‌ها را نمی‌دید (دمو خط را مستقیم در دیتابیس می‌ساخت). حالا ذخیره خط را می‌سازد، اگر ایزومتریک در MDR زیر ساب‌سیستمی باشد خط را همان‌جا ثبت می‌کند، و تجهیز خط را از اولین تای‌این نقشه می‌شناسد؛ خط‌های بی‌ساب‌سیستم هم در صفحهٔ «سیستم و ساب‌سیستم» با فرم ثبت نشان داده می‌شوند.");
  w("- **پیام رد RFC/RFSU** نام خام «punch» را نشان می‌داد؛ حالا «Punch A/B باز (1)».");
  w();
  return out.join("\n");
}

const PARTY_FA = { contractor: "پیمانکار", company: "کارفرما", tpi: "TPI" };
